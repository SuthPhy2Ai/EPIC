class EDLEnergyLoss(torch.nn.Module):
    """
    Evidential Deep Learning loss for energy prediction with uncertainty.

    Combines negative log-likelihood (NLL) and regularization terms with
    lambda annealing during training.

    Args:
        lambda_max: Maximum lambda value for regularization weight
        lambda_schedule: Annealing schedule ('linear' or 'exponential')
        lambda_start_epoch: Epoch to start lambda annealing
    """
    def __init__(
        self,
        lambda_max: float = 0.01,
        lambda_schedule: str = "linear",
        lambda_start_epoch: int = 0,
    ):
        super().__init__()
        self.register_buffer(
            "lambda_max",
            torch.tensor(lambda_max, dtype=torch.get_default_dtype()),
        )
        self.lambda_schedule = lambda_schedule
        self.lambda_start_epoch = lambda_start_epoch
        self.current_lambda = 0.0

    def update_lambda(self, epoch: int, max_epochs: int):
        """
        Update lambda value based on annealing schedule.

        Args:
            epoch: Current epoch
            max_epochs: Total number of epochs
        """
        if epoch < self.lambda_start_epoch:
            self.current_lambda = 0.0
            return

        adjusted_epoch = epoch - self.lambda_start_epoch
        adjusted_max = max_epochs - self.lambda_start_epoch

        if self.lambda_schedule == "linear":
            self.current_lambda = float(
                self.lambda_max * (adjusted_epoch / adjusted_max)
            )
        elif self.lambda_schedule == "exponential":
            k = 5.0 / adjusted_max
            self.current_lambda = float(
                self.lambda_max * (1 - torch.exp(-k * adjusted_epoch))
            )

    def forward(
        self, ref: Batch, pred: TensorDict, ddp: Optional[bool] = None
    ) -> torch.Tensor:
        """
        Compute EDL loss for energy prediction.

        Args:
            ref: Reference batch containing true energies
            pred: Predictions containing gamma, nu, alpha, beta
            ddp: Whether to use DDP reduction

        Returns:
            Scalar loss value
        """
        # Extract predictions
        gamma = pred["energy"]  # Energy mean [n_graphs]
        nu = pred["energy_nu"]  # Evidence count [n_graphs]
        alpha = pred["energy_alpha"]  # Gamma shape [n_graphs]
        beta = pred["energy_beta"]  # Gamma scale [n_graphs]

        # Extract ground truth
        energy_true = ref["energy"]  # [n_graphs]

        # Compute squared error
        squared_error = (energy_true - gamma) ** 2

        # NLL term (negative log-likelihood)
        # For scalar: 0.5 * [log(π/ν) + log(β/α) + (α/β) + (ν/(ν+1))*error²]
        pi = torch.tensor(3.14159265359, device=gamma.device, dtype=gamma.dtype)
        nll = 0.5 * (
            torch.log(pi / (nu + 1e-8))
            + torch.log((beta + 1e-8) / (alpha + 1e-8))
            + (alpha / (beta + 1e-8))
            + (nu / (nu + 1)) * squared_error
        )

        # Regularization term
        # Encourages appropriate uncertainty: |error| * (2ν + α)
        error_abs = torch.sqrt(squared_error + 1e-8)
        reg = error_abs * (2 * nu + alpha)

        # Combined loss with lambda weighting
        raw_loss = nll + self.current_lambda * reg

        return reduce_loss(raw_loss, ddp)


class FullNIGEnergyLoss(torch.nn.Module):
    """
    Full NIG (Normal-Inverse-Gamma) marginal likelihood loss from Amini et al.

    Uses the complete Student-t marginal likelihood derived from NIG prior,
    which includes the Omega term that prevents unbounded evidence growth.

    Reference: Amini et al., "Deep Evidential Regression" (NeurIPS 2020)

    Args:
        lambda_max: Maximum lambda value for regularization weight
        lambda_schedule: Annealing schedule ('linear' or 'exponential')
        lambda_start_epoch: Epoch to start lambda annealing
    """
    def __init__(
        self,
        lambda_max: float = 0.01,
        lambda_schedule: str = "linear",
        lambda_start_epoch: int = 0,
    ):
        super().__init__()
        self.register_buffer(
            "lambda_max",
            torch.tensor(lambda_max, dtype=torch.get_default_dtype()),
        )
        self.lambda_schedule = lambda_schedule
        self.lambda_start_epoch = lambda_start_epoch
        self.current_lambda = 0.0

    def update_lambda(self, epoch: int, max_epochs: int):
        """Update lambda value based on annealing schedule."""
        if epoch < self.lambda_start_epoch:
            self.current_lambda = 0.0
            return

        adjusted_epoch = epoch - self.lambda_start_epoch
        adjusted_max = max_epochs - self.lambda_start_epoch

        if self.lambda_schedule == "linear":
            self.current_lambda = float(
                self.lambda_max * (adjusted_epoch / adjusted_max)
            )
        elif self.lambda_schedule == "exponential":
            k = 5.0 / adjusted_max
            self.current_lambda = float(
                self.lambda_max * (1 - torch.exp(-k * adjusted_epoch))
            )

    def forward(
        self, ref: Batch, pred: TensorDict, ddp: Optional[bool] = None
    ) -> torch.Tensor:
        """
        Compute full NIG marginal likelihood loss.

        NLL = 0.5*log(π/ν) - α*log(Ω) + (α+0.5)*log(error²*ν + Ω) + log(Γ(α)/Γ(α+0.5))
        where Ω = 2β(1+ν)
        """
        # Extract predictions
        gamma = pred["energy"]
        nu = pred["energy_nu"]
        alpha = pred["energy_alpha"]
        beta = pred["energy_beta"]
        energy_true = ref["energy"]

        # Compute error
        error = energy_true - gamma
        squared_error = error ** 2

        # Compute Omega = 2*beta*(1 + nu)
        omega = 2.0 * beta * (1.0 + nu)

        # Full NIG NLL
        pi = torch.tensor(3.14159265359, device=gamma.device, dtype=gamma.dtype)

        nll = (
            0.5 * torch.log(pi / (nu + 1e-8))
            - alpha * torch.log(omega + 1e-8)
            + (alpha + 0.5) * torch.log(squared_error * nu + omega + 1e-8)
            + torch.lgamma(alpha + 1e-8) - torch.lgamma(alpha + 0.5 + 1e-8)
        )

        # Regularization term (same as simplified version)
        error_abs = torch.sqrt(squared_error + 1e-8)
        reg = error_abs * (2 * nu + alpha)

        # Combined loss
        raw_loss = nll + self.current_lambda * reg

        return reduce_loss(raw_loss, ddp)


def mean_squared_error_energy(
    ref: Batch, pred: TensorDict, ddp: Optional[bool] = None
) -> torch.Tensor:
    raw_loss = torch.square(ref["energy"] - pred["energy"])
    return reduce_loss(raw_loss, ddp)


def weighted_mean_squared_error_energy(
    ref: Batch, pred: TensorDict, ddp: Optional[bool] = None
) -> torch.Tensor:
    # Calculate per-graph number of atoms.
    num_atoms = ref.ptr[1:] - ref.ptr[:-1]  # shape: [n_graphs]
    raw_loss = (
        ref.weight
        * ref.energy_weight
        * torch.square((ref["energy"] - pred["energy"]) / num_atoms)
    )
    return reduce_loss(raw_loss, ddp)


def weighted_mean_absolute_error_energy(
    ref: Batch, pred: TensorDict, ddp: Optional[bool] = None
) -> torch.Tensor:
    num_atoms = ref.ptr[1:] - ref.ptr[:-1]
    raw_loss = (
        ref.weight
        * ref.energy_weight
        * torch.abs((ref["energy"] - pred["energy"]) / num_atoms)
    )
    return reduce_loss(raw_loss, ddp)


